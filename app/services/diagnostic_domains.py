def _soft_domain_hits(clean: str, domain_key: str) -> tuple[list[str], list[str]]:
    groups = SOFT_DOMAIN_PATTERNS.get(domain_key, ())
    matched_groups: list[str] = []
    matched_patterns: list[str] = []

    for group_name, patterns in groups:
        for pattern in patterns:
            if re.search(pattern, clean, re.IGNORECASE):
                matched_groups.append(group_name)
                matched_patterns.append(pattern)
                break

    unique_groups = sorted(set(matched_groups))
    if not unique_groups:
        return [], []

    # Один тонкий признак не должен тащить домен.
    # Нужны хотя бы две разные смысловые группы.
    if len(unique_groups) >= 2:
        return [f"soft:{group}" for group in unique_groups], matched_patterns[:5]

    # Исключения: для острых доменов один сильный мягкий паттерн может быть важным,
    # но он все равно идет как supporting, чтобы модель не ставила диагноз.
    high_sensitivity_domains = {
        "suicide_self_harm",
        "psychosis_prodrome",
        "delirium_cognitive",
        "somatic_substance",
        "addiction_withdrawal",
    }
    if domain_key in high_sensitivity_domains:
        return [], [f"soft:{group}" for group in unique_groups] + matched_patterns[:4]

    return [], matched_patterns[:5]



def analyze_clinical_domains(text: str, *, limit: int = 3) -> list[dict[str, object]]:
    clean = _normalize(text)
    if not clean:
        return []

    candidates: list[dict[str, object]] = []
    for domain in DOMAINS:
        primary_hits = _marker_hits(clean, domain.primary_markers)
        supporting_hits = _marker_hits(clean, domain.supporting_markers)
        soft_primary_hits, soft_supporting_hits = _soft_domain_hits(clean, domain.key)

        primary_hits = list(dict.fromkeys(primary_hits + soft_primary_hits))
        supporting_hits = list(dict.fromkeys(supporting_hits + soft_supporting_hits))

        if not primary_hits and len(supporting_hits) < 2:
            continue

        score = len(primary_hits) * 3 + len(supporting_hits)
        if any(str(hit).startswith("soft:") for hit in primary_hits):
            score += 2
        if primary_hits and supporting_hits:
            score += 2
        if len(primary_hits) >= 2:
            score += 2

        candidates.append(
            {
                "key": domain.key,
                "title": domain.title,
                "score": score,
                "tags": domain.knowledge_tags,
                "primary_hits": primary_hits[:5],
                "supporting_hits": supporting_hits[:5],
                "question_focus": domain.question_focus,
            }
        )

    return sorted(candidates, key=lambda item: int(item["score"]), reverse=True)[:limit]


def format_domain_context(domains: list[dict[str, object]]) -> str:
    if not domains:
        return ""

    lines = [
        "Вероятные клинические домены для осторожной проверки. Это не диагнозы, "
        "а подсказки для выбора вопросов, оценки риска и дифференциальных гипотез:"
    ]
    for domain in domains:
        focus = "; ".join(str(item) for item in domain.get("question_focus", ()))
        lines.append(f"- {domain['title']}: уточнить {focus}.")
    return "\n".join(lines)
